# Challenge 1: create a function that returns the square of anumber 
def square(number):
    """ This function returns the square of a number."""
    return number ** 2


# Challenge 2: create a function that checks if a number is even or odd
def is_even(num):
    """
    This function checks if a number is even or odd.
    """
    return num % 2 == 0
        




# Challenge 3: Scope of variables
def calculate_total(price, quantity):
    """
    This function calculates the total cost based on price and quantity."""
    return price * quantity
